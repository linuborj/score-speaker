/** UI strings for a BCP-47 language code: Swedish for "sv", else English. */
fun uiStrings(language: String): Strings =
    if (language == "sv") SwedishStrings else EnglishStrings

val LocalStrings = staticCompositionLocalOf { EnglishStrings }
