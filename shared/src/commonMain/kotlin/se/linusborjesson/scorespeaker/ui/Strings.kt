package se.linusborjesson.scorespeaker.ui

import androidx.compose.runtime.Immutable
import androidx.compose.runtime.staticCompositionLocalOf
import se.linusborjesson.scorespeaker.settings.BindableAction

/**
 * Every user-facing UI string, in one language. Provided via [LocalStrings]
 * (Android selects by the language setting; English is the default and the
 * fallback). Pipeline diagnostics on the debug panel (detection method,
 * fps, cache line) stay raw — they're data, not copy.
 *
 * `%d`/`%s` fields are `String.format`-style templates; callers format.
 */
@Immutable
data class Strings(
    // Live screen
    val locked: String,
    val searching: String,
    val historyChip: String,
    val settingsChip: String,
    val backChip: String,
    val backDescription: String,
    val cameraPermissionRequired: String,
    val cameraUnavailable: String,
    val readoutShot: String,
    val readoutScore: String,
    // Settings
    val settingsTitle: String,
    val voiceAndSpeech: String,
    val speechRate: String,
    /** Spoken value for the speech-rate slider; %s = rate like "1.1". */
    val speechRateTimesTemplate: String,
    val language: String,
    val languageSystem: String,
    val languageEnglish: String,
    val languageSwedish: String,
    val announcements: String,
    val scoreAfterEachShot: String,
    val aimOffset: String,
    val aimOffsetSub: String,
    val misses: String,
    val missesSub: String,
    val offsetDecimals: String,
    val offsetDecimalsSub: String,
    val offsetStyle: String,
    val offsetStyleDirections: String,
    val offsetStyleClock: String,
    val verbosity: String,
    val verbosityTerse: String,
    val verbosityNormal: String,
    val keyBindings: String,
    val bindingListeningSub: String,
    val bindingNotBoundSub: String,
    val listeningChip: String,
    val clearChip: String,
    /** %s = action label. */
    val clearBindingForTemplate: String,
    val actionReadLastShot: String,
    val actionReadAvgError: String,
    // Camera group
    val camera: String,
    val cameraZoom: String,
    val cameraZoomSub: String,
    // About group
    val about: String,
    val privacyPolicy: String,
    val privacyPolicySub: String,
    val ossLicenses: String,
    val ossLicensesSub: String,
    // Developer group + debug panel
    val developer: String,
    val debugOverlays: String,
    val debugOverlaysSub: String,
    val autoCaptureShots: String,
    val autoCaptureShotsSub: String,
    // Experimental
    val captureChip: String,
    // History
    val historyTitle: String,
    val lastThirtyDays: String,
    val avgPerShot: String,
    val sessions: String,
    val noSessionsYet: String,
    val bestSessionAvg: String,
    val totalShots: String,
    /** %d = shot count. */
    val shotsCountTemplate: String,
    /** %s = formatted average. */
    val avgTemplate: String,
    /** %d = missed count. */
    val missedTemplate: String,
    /** %d = missed count, %s = comma-joined shot numbers. */
    val missedListTemplate: String,
    /** %d = session index. */
    val sessionTitleTemplate: String,
    /** %d = whole minutes. */
    val minutesTemplate: String,
    // Session detail
    val statTotal: String,
    val statAvg: String,
    val statBest: String,
    val statShots: String,
    val shotGroup: String,
    val shotLog: String,
    val noShots: String,
    // Shot-note words ("Low-right 1.2" / "Centre")
    val noteCentre: String,
    val noteLow: String,
    val noteHigh: String,
    val noteLeft: String,
    val noteRight: String,
) {
    fun actionLabel(action: BindableAction): String = when (action) {
        BindableAction.READ_LAST_SCORE -> actionReadLastShot
        BindableAction.READ_AVG_ERROR_5 -> actionReadAvgError
    }
}

